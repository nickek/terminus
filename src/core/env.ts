import { execFileSync } from 'child_process';
import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';

/**
 * When the core is started from a non-interactive shell (e.g. wsl.exe from the Windows app),
 * ~/.bashrc never runs, so PATH misses things like ~/.local/bin where `claude` lives.
 * Ask the user's interactive login shell for its PATH and merge it in, so the core, the
 * sessions it spawns and the tools those run see the same PATH as a normal terminal.
 */
export function adoptUserShellPath() {
  const shell = process.env.SHELL || '/bin/bash';
  let shellPath = '';
  try {
    const out = execFileSync(shell, ['-lic', 'printf "\\n__TERMINUS_PATH__%s\\n" "$PATH"'], {
      encoding: 'utf8',
      timeout: 8000,
      stdio: ['ignore', 'pipe', 'ignore'],
      env: { ...process.env, TERM: 'dumb' },
    });
    shellPath = /__TERMINUS_PATH__(.*)/.exec(out)?.[1] || '';
  } catch {}
  const home = os.homedir();
  const extras = [path.join(home, '.local', 'bin'), path.join(home, '.claude', 'local'), path.join(home, 'bin')];
  const merged: string[] = [];
  for (const p of [...shellPath.split(':'), ...(process.env.PATH || '').split(':'), ...extras]) {
    if (p && !merged.includes(p)) merged.push(p);
  }
  process.env.PATH = merged.join(':');
}

function isExecutable(p: string) {
  try {
    fs.accessSync(p, fs.constants.X_OK);
    return fs.statSync(p).isFile();
  } catch {
    return false;
  }
}

/** Find an executable on PATH (plus common install locations). Returns an absolute path or undefined. */
export function findExecutable(name: string, extraDirs: string[] = []): string | undefined {
  if (name.includes('/')) return isExecutable(name) ? name : undefined;
  for (const dir of [...(process.env.PATH || '').split(':'), ...extraDirs]) {
    if (!dir) continue;
    const p = path.join(dir, name);
    if (isExecutable(p)) return p;
  }
  return undefined;
}

/**
 * Arguments that start the user's shell the way a normal terminal would, so their own
 * startup files (prompt, aliases, functions, PATH) load natively — nothing is copied or parsed.
 *
 * bash: a login shell skips ~/.bashrc and a non-login shell skips the profile files, so we
 * start an interactive shell with a tiny rcfile that runs both (profile first, then ~/.bashrc
 * unless the profile already sources it). zsh/fish: interactive login covers everything.
 */
export function shellLaunchArgs(shell: string): string[] {
  const name = path.basename(shell);
  if (name === 'bash') return ['--rcfile', bashInitFile(), '-i'];
  if (name === 'zsh' || name === 'fish') return ['-l', '-i'];
  return ['-l'];
}

function bashInitFile(): string {
  const dir = path.join(process.env.TERMINUS_HOME || path.join(os.homedir(), '.terminus'), 'shell');
  const file = path.join(dir, 'bash-init.sh');
  const content = `# Generated by Terminus — starts bash like a terminal would (login files + ~/.bashrc).
[ -f /etc/profile ] && . /etc/profile
__terminus_profile=
for __f in "$HOME/.bash_profile" "$HOME/.bash_login" "$HOME/.profile"; do
  if [ -f "$__f" ]; then . "$__f"; __terminus_profile="$__f"; break; fi
done
# Load ~/.bashrc unless the profile file already does.
if [ -f "$HOME/.bashrc" ] && ! { [ -n "$__terminus_profile" ] && grep -qs 'bashrc' "$__terminus_profile"; }; then
  . "$HOME/.bashrc"
fi
unset __f __terminus_profile
`;
  try {
    fs.mkdirSync(dir, { recursive: true });
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content) fs.writeFileSync(file, content);
  } catch {}
  return file;
}
